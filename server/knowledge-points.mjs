function slugify(stage, subject, index, id) {
  if (id) return id;
  const stageSlug = { 小学: 'primary', 初中: 'middle', 高中: 'high' }[stage];
  const subjectSlug = { 语文: 'chinese', 数学: 'math', 英语: 'english', 物理: 'physics', 化学: 'chemistry', 生物: 'biology', 地理: 'geography' }[subject];
  return `${stageSlug}-${subjectSlug}-${index + 1}`;
}

const points = Object.entries(stageSubjectSeeds).flatMap(([stage, subjects]) =>
    Object.entries(subjects).flatMap(([subject, seeds]) =>
    seeds.map(([name, description], index) => {
      const explicitId = name === 'primary-math-fractions' ? name : null;
      const title = explicitId ? '分数' : name;
      return {
        id: slugify(stage, subject, index, explicitId),
        stage,
        subject,
        name: title,
        description,
        examples: [
          `${title}基础练习`,
          `${title}综合应用`,
        ],
      };
    }),
  ),
);

export function getKnowledgePoints() {
  return points.map((point) => ({ ...point, examples: [...point.examples] }));
}

export function findKnowledgePoint(id) {
  return points.find((point) => point.id === id) ?? null;
}
